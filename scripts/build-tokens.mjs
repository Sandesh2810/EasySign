// Generates src/app/tokens.css from design/alterme-tokens.json (the single source of theme values).
// Run: npm run tokens      Check only (CI / verify): node scripts/build-tokens.mjs --check
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(path.join(root, 'design', 'alterme-tokens.json'), 'utf8'));
const out = path.join(root, 'src', 'app', 'tokens.css');

const decl = (obj, indent = '  ') =>
  Object.entries(obj)
    .map(([k, v]) => `${indent}--${k}: ${v};`)
    .join('\n');

const add = t.easysign.added;
const light = {
  ...t.color.light,
  ...t.color.accent,
  'control-border': add['control-border-light'].value,
  'on-ink': add['on-ink'].light,
  success: add['semantic-success'].light,
  warning: add['semantic-warning'].light,
  danger: add['semantic-danger'].light,
};
const dark = {
  ...t.color.dark,
  'control-border': add['control-border-dark'].value,
  'on-ink': add['on-ink'].dark,
  success: add['semantic-success'].dark,
  warning: add['semantic-warning'].dark,
  danger: add['semantic-danger'].dark,
};
const gradients = Object.fromEntries(Object.entries(t.gradient).map(([k, v]) => [`gradient-${k}`, v]));

const themeMap = {
  ...Object.fromEntries(Object.keys(light).map((k) => [`color-${k}`, `var(--${k})`])),
  ...Object.fromEntries(Object.entries(t.radius).map(([k, v]) => [`radius-${k}`, v])),
  ...Object.fromEntries(Object.entries(t.shadow).map(([k, v]) => [`shadow-${k}`, v])),
  'font-sans': `var(--font-hanken), ${t.font.sans}`,
  'font-serif': `var(--font-garamond), ${t.font.serif}`,
  'font-mono': t.font.mono,
  'ease-standard': t.motion.easing,
};

const css = `/* GENERATED by scripts/build-tokens.mjs from design/alterme-tokens.json. Do not edit by hand. */
:root,
[data-theme="light"] {
${decl(light)}
${decl(gradients)}
  --blur-glass: ${t.blur.glass};
  --blur-glass-strong: ${t.blur['glass-strong']};
  --duration-fast: ${t.motion.duration.fast};
  --duration-base: ${t.motion.duration.base};
  color-scheme: light;
}

[data-theme="dark"] {
${decl(dark)}
  color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${decl(dark, '    ')}
    color-scheme: dark;
  }
}

@theme inline {
${decl(themeMap)}
}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== css) {
    console.error('tokens.css is out of date. Run: npm run tokens');
    process.exit(1);
  }
  console.log('tokens.css is up to date.');
} else {
  writeFileSync(out, css);
  console.log(`Wrote ${path.relative(root, out)}`);
}
